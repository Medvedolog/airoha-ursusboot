static void ursus_logf(const char *fmt, ...)
{
    char line[384];
    va_list ap;
    int n;

    va_start(ap, fmt);
    n = vsnprintf(line, sizeof(line), fmt, ap);
    va_end(ap);
    if (n < 0)
        return;
    line[sizeof(line) - 1] = 0;
    printf("%s", line);
    n = strlen(line);
    if ((size_t)n + ursus_web_log_len + 1 >= sizeof(ursus_web_log)) {
        const char *mark = "[... earlier log truncated ...]\n";
        ursus_web_log_len = 0;
        strcpy(ursus_web_log, mark);
        ursus_web_log_len = strlen(mark);
    }
    memcpy(ursus_web_log + ursus_web_log_len, line, n);
    ursus_web_log_len += n;
    ursus_web_log[ursus_web_log_len] = 0;
}

static const char *ursus_skip_ows(const char *p)
{
    while (*p == ' ' || *p == '\t')
        p++;
    return p;
}

static bool ursus_parse_header_value(const char *h, const char *name,
                                     char *out, size_t out_len)
{
    const char *p = h;
    size_t n = strlen(name);

    if (!out || out_len < 2)
        return false;
    out[0] = 0;
    while (*p) {
        if (!strncasecmp(p, name, n) && p[n] == ':') {
            const char *v = ursus_skip_ows(p + n + 1);
            const char *e = v;
            size_t len;

            while (*e && *e != '\r' && *e != '\n')
                e++;
            while (e > v && (e[-1] == ' ' || e[-1] == '\t'))
                e--;
            len = e - v;
            if (!len || len >= out_len)
                return false;
            memcpy(out, v, len);
            out[len] = 0;
            return true;
        }
        p = strchr(p, '\n');
        if (!p)
            break;
        p++;
    }
    return false;
}

static bool ursus_parse_header_ulong(const char *h, const char *name, size_t *value)
{
    char tmp[32];
    char *end;
    ulong v;

    if (!value || !ursus_parse_header_value(h, name, tmp, sizeof(tmp)))
        return false;
    v = simple_strtoul(tmp, &end, 10);
    if (end == tmp || *end)
        return false;
    *value = (size_t)v;
    return true;
}

static int ursus_hex_digit(char c)
{
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

static bool ursus_decode_filename(const char *encoded, char *out, size_t out_len)
{
    size_t i = 0, o = 0;

    if (!encoded || !*encoded || !out || out_len < 2)
        return false;
    while (encoded[i] && o + 1 < out_len) {
        unsigned char ch = encoded[i++];
        if (ch == '%' && encoded[i] && encoded[i + 1]) {
            int hi = ursus_hex_digit(encoded[i]);
            int lo = ursus_hex_digit(encoded[i + 1]);
            if (hi < 0 || lo < 0)
                return false;
            ch = (hi << 4) | lo;
            i += 2;
        }
        if (ch < 0x20 || ch == 0x7f || ch == '"' || ch == '\\')
            ch = '_';
        out[o++] = ch;
    }
    if (encoded[i])
        return false;
    out[o] = 0;
    return o != 0;
}

static bool ursus_generation_valid(const char *g)
{
    size_t i, n;

    if (!g)
        return false;
    n = strlen(g);
    if (n < 8 || n >= URSUS_GENERATION_MAX)
        return false;
    for (i = 0; i < n; i++) {
        char c = g[i];
        if (!((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
              (c >= '0' && c <= '9') || c == '-' || c == '_' || c == '.'))
            return false;
    }
    return true;
}

static int ursus_header_parser_selftest(void)
{
    const char *h = "POST /api/firmware-chunk HTTP/1.1\r\n"
                    "Content-Length: 65536\r\n"
                    "X-Ursus-Offset: 0\r\n"
                    "X-Ursus-Total:\t10518808\r\n\r\n";
    size_t clen = 0, off = 1, total = 0;

    if (!ursus_parse_header_ulong(h, "Content-Length", &clen) || clen != 65536 ||
        !ursus_parse_header_ulong(h, "X-Ursus-Offset", &off) || off != 0 ||
        !ursus_parse_header_ulong(h, "X-Ursus-Total", &total) || total != 10518808) {
        printf("URSUS_HTTP_HEADER_SELFTEST_FAIL clen=%u off=%u total=%u\n",
               (unsigned int)clen, (unsigned int)off, (unsigned int)total);
        return -EINVAL;
    }
    printf("URSUS_HTTP_HEADER_SELFTEST_PASS\n");
    return 0;
}

